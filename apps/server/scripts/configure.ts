// First-time setup: creates .env with the password hash and VAPID keys.
// Interactive:      pnpm configure
// Non-interactive:  NONSTOP_PASSWORD=... pnpm configure
// Re-running keeps existing VAPID keys (installed devices stay subscribed) and only changes the password.
import fs from 'node:fs';
import path from 'node:path';
import readline from 'node:readline';
import dotenv from 'dotenv';
import webpush from 'web-push';
import { hashPassword } from '../src/auth.ts';
import { repoRoot } from '../src/config.ts';

const envPath = process.env.NONSTOP_ENV_FILE ?? path.join(repoRoot, '.env');

function askHidden(question: string): Promise<string> {
  return new Promise((resolve) => {
    const rl = readline.createInterface({ input: process.stdin, output: process.stdout, terminal: true });
    const out = rl as unknown as { _writeToOutput: (s: string) => void; output: NodeJS.WriteStream };
    let prompted = false;
    out._writeToOutput = (s: string) => {
      if (!prompted) {
        out.output.write(s);
        prompted = true;
      }
    };
    rl.question(question, (answer) => {
      rl.close();
      process.stdout.write('\n');
      resolve(answer);
    });
  });
}

async function main() {
  const existing = fs.existsSync(envPath) ? dotenv.parse(fs.readFileSync(envPath)) : {};

  let password = process.env.NONSTOP_PASSWORD ?? '';
  if (!password) {
    password = await askHidden('Password NonsTop (min 8 karakter): ');
    const again = await askHidden('Ulangi password: ');
    if (password !== again) throw new Error('Password tidak sama.');
  }
  if (password.length < 8) throw new Error('Password minimal 8 karakter.');

  const vapid =
    existing.VAPID_PUBLIC_KEY && existing.VAPID_PRIVATE_KEY
      ? { publicKey: existing.VAPID_PUBLIC_KEY, privateKey: existing.VAPID_PRIVATE_KEY }
      : webpush.generateVAPIDKeys();

  const values: Record<string, string> = {
    HOST: '127.0.0.1',
    PORT: '8787',
    COOKIE_SECURE: 'auto',
    BACKUP_HOUR: '3',
    BACKUP_KEEP_DAYS: '14',
    ...existing,
    NONSTOP_PASSWORD_HASH: hashPassword(password),
    VAPID_PUBLIC_KEY: vapid.publicKey,
    VAPID_PRIVATE_KEY: vapid.privateKey,
  };
  const body = Object.entries(values)
    .map(([k, v]) => `${k}='${v}'`)
    .join('\n');
  fs.writeFileSync(envPath, `# Generated by "pnpm configure". Do not commit.\n${body}\n`, { mode: 0o600 });
  console.log(`Saved ${envPath}.`);
}

main().catch((err) => {
  console.error(err instanceof Error ? err.message : err);
  process.exit(1);
});
